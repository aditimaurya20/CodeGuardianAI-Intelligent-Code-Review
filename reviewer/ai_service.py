def analyze_code_with_ai(code, static_results, language="Python"):
    print("AI SERVICE ENTERED")
    static_report = format_static_analysis(
        static_results,
        language
    )

    api_key = os.getenv("OPENROUTER_API_KEY")

    if not api_key:
        return {
            "success": False,
            "review": "",
            "error": "OPENROUTER_API_KEY is not configured."
        }

    url = "https://openrouter.ai/api/v1/chat/completions"

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }

    prompt = f"""
    You are an expert {language} software code reviewer.

    The source code is written in {language}.
    Analyze the source code together with the results generated by static analysis tools.

    Do not blindly repeat static-analysis findings.
    Verify important findings against the source code.

    ================ SOURCE CODE ================

    {code}

    ================ STATIC ANALYSIS ================

    {static_report}

    ================ REVIEW REQUIREMENTS ================

    Identify:
    - Important bugs and potential bugs
    - Code quality problems
    - Performance problems
    - Security vulnerabilities
    - Complexity problems
    - Maintainability problems
    - Practical improvement suggestions
    - A genuinely optimized version of the code

    IMPORTANT:
    - Do not reveal your reasoning process.
    - Do not write analysis about how you reached your conclusions.
    - Do not write phrases such as "Let's think", "Let's derive", "Let's analyze", "Actually", "Now produce", or similar reasoning text.
    - Return only the final review.

    ================ OPTIMIZED CODE RULES ================

    The optimized code MUST:
    - Remain in {language}.
    - Preserve the original behavior and output.
    - Include the complete source code.
    - Include every original function, class, import, and required top-level executable code.
    - Fix actionable static-analysis issues whenever they can be safely fixed without changing behavior.
    - Fix formatting and style issues when they can be safely fixed.
    - Reduce unnecessary lines, nested conditions, duplicate logic, and redundant operations where possible.
    - Improve readability and maintainability.
    - Avoid unnecessary imports.
    - Avoid unnecessary type annotations.
    - Avoid unnecessary constants.
    - Avoid unnecessary comments, docstrings, or boilerplate unless required for correctness.
    - Not become longer unless there is a clear technical reason.
    - Preserve normal {language} syntax and indentation.
    - Remain valid and executable {language} code.
    - Never convert the code to another programming language.
    - Never return only a portion of the source code.
    - Never return "No optimization required" when actionable issues are present.
    - If the original code is already reasonably optimized, make only necessary changes.

    ================ FINAL RESPONSE FORMAT ================

    Return EXACTLY these sections and in this exact order:

    BUGS:
    - ...

    CODE QUALITY:
    - ...

    PERFORMANCE:
    - ...

    SECURITY:
    - ...

    COMPLEXITY:
    - ...

    MAINTAINABILITY:
    - ...

    SUGGESTIONS:
    - ...

    OPTIMIZED CODE:
    ```{language}
    complete optimized source code
    ```
    ================ STRICT OUTPUT RULES ================

    Keep the entire review concise and presentation-friendly.

    BUGS:
    - Report only confirmed bugs or correctness errors.
    - Maximum 3 bullets.
    - Each bullet must contain only ONE short sentence.
    - NEVER explain, justify, calculate, debate, question, or verify whether something is a bug.
    - NEVER mention uncertainty such as "might be", "could be", "potential", "maybe", "I'm not sure", or "if the intention is".
    - NEVER describe the input/output to prove a bug.
    - NEVER repeat the source code.
    - If a problem is uncertain or depends on an unknown requirement, DO NOT report it.
    - Security issues belong only in SECURITY.
    - Performance issues belong only in PERFORMANCE.
    - Style issues belong only in CODE QUALITY.
    - If there are no confirmed bugs, output exactly:
    None detected.

    CODE QUALITY:
    - Maximum 4 bullets.
    - Each bullet must be one short sentence.
    - Mention only the most important quality issues.
    - If no issues exist, write exactly: None detected.

    PERFORMANCE:
    - Maximum 2 bullets.
    - Each bullet must be one short sentence.
    - Mention only meaningful performance concerns.
    - If no issues exist, write exactly: None detected.

    SECURITY:
    - Maximum 3 bullets.
    - Each bullet must be one short sentence.
    - Prioritize actual security vulnerabilities.
    - If no issues exist, write exactly: None detected.

    COMPLEXITY:
    - Maximum 2 bullets.
    - Each bullet must be one short sentence.
    - Mention complexity level and important complexity concerns.
    - If no issues exist, write exactly: None detected.

    MAINTAINABILITY:
    - Maximum 3 bullets.
    - Each bullet must be one short sentence.
    - Mention only the most important maintainability issues.
    - If no issues exist, write exactly: None detected.

    SUGGESTIONS:
    - Maximum 3 bullets.
    - Each bullet must be one concise actionable sentence.
    - Do not repeat issues already explained above.
    - Do not include optimized code or code fragments.

    OPTIMIZED CODE:
    Immediately output exactly ONE fenced code block.
    The code block MUST contain the complete optimized source code.
    Do not write any explanation before or after the code block.
    Do not leave OPTIMIZED CODE empty.
    Do not create additional sections.
    Do not repeat optimized code in SUGGESTIONS.
    The optimized code must be correct, clean, efficient, and production-quality.
    Fix all confirmed errors and issues identified by static analysis.
    Optimization must make meaningful improvements to the code, not just formatting changes.
    Prioritize correctness, security, performance, algorithmic efficiency, memory efficiency, and maintainability.
    Do not consider whitespace, indentation, spacing, or formatting alone as an optimization.
    Improve inefficient algorithms, loops, repeated operations, memory usage, or data structures when a meaningful improvement is justified by the code's actual usage.
    Only change the algorithm or data structure when the change improves efficiency, memory usage, correctness, or maintainability.
    Do not make unnecessary changes when the existing implementation is already correct and efficient.
    Preserve the intended behavior and output of the original program unless a change is required to fix a confirmed issue.
    The optimized code must not contain comments or docstrings.
    Do not rewrite or shorten code merely for style.
    Preserve all original program components and executable statements unless a change is required for correctness, security, performance, or maintainability.
    The optimized code must include the complete source code from the first line through the final line.

    FINAL CHECK:
    Verify that the optimized code is complete and valid.
    Verify that all original program components are preserved.
    Verify that actionable issues are safely fixed.
    Do not reveal this verification process.
    Before responding, remove every sentence that explains your reasoning, uncertainty, calculations, or decision process.
    The final response must contain conclusions only, never reasoning.
    """

    data = {
        "model": "openrouter/free",
        "messages": [
            {
                "role": "user",
                "content": prompt
            }
        ],
        "temperature": 0.2,
        "max_tokens": 10000
    }

    try:
        print("OPENROUTER REQUEST STARTED")
        response = requests.post(
            url,
            headers=headers,
            json=data,
            timeout=180
        )
        print("OPENROUTER RESPONSE:", response.status_code)

        if response.status_code != 200:
            print("OPENROUTER ERROR:", response.text)
            return {
                "success": False,
                "review": "",
                "error": response.text
            }

        result = response.json()
        print("OPENROUTER RESPONSE RECEIVED")
        print("OPENROUTER RESULT KEYS:", result.keys())

        if result.get("error"):
            print("OPENROUTER JSON ERROR:", result.get("error"))
            return {
                "success": False,
                "review": "",
                "error": str(result.get("error"))
            }

        choices = result.get("choices") or []
        print("OPENROUTER CHOICES:", len(choices))

        if not choices:
            return {
                "success": False,
                "review": "",
                "error": "AI service returned no choices."
            }

        message = choices[0].get("message") or {}
        content = message.get("content")

        if isinstance(content, list):
            content_parts = []

            for part in content:
                if isinstance(part, dict):
                    text = part.get("text")
                    if text:
                        content_parts.append(text)
                elif isinstance(part, str):
                    content_parts.append(part)

            content = "\n".join(content_parts)

        if not isinstance(content, str):
            content = str(content or "")

        content = content.strip()

        
        if not content:
            choice = choices[0]
            finish_reason = choice.get("finish_reason", "unknown")

            print("OPENROUTER EMPTY CONTENT")
            print("FINISH REASON:", finish_reason)

            return {
                "success": False,
                "review": "",
                "error": (
                    "AI returned an empty response. "
                    f"Finish reason: {finish_reason}. "
                    "Please try again with a smaller file."
                )
            }


        return {
            "success": True,
            "review": content
        }

    except requests.exceptions.Timeout:
        return {
            "success": False,
            "review": "",
            "error": "AI analysis timed out. Please try again."
        }

    except requests.exceptions.RequestException as e:
        print("OPENROUTER REQUEST ERROR:", repr(e))
        return {
            "success": False,
            "review": "",
            "error": str(e)
        }
    except Exception as e:
        print("OPENROUTER GENERAL ERROR:", repr(e))
        return {
            "success": False,
            "review": "",
            "error": str(e)
        }

def format_static_analysis(static_results, language="Python"):
    text = []
    text.append("=== LANGUAGE ===")
    text.append(language)

    tool_sections = [
        ("pylint", "PYLINT ANALYSIS"),
        ("flake8", "FLAKE8 ANALYSIS"),
        ("bandit", "BANDIT SECURITY ANALYSIS"),
        ("radon", "RADON ANALYSIS")
    ]

    for tool, title in tool_sections:
        result = static_results.get(tool)
        text.append(f"\n=== {title} ===")

        if not isinstance(result, dict):
            text.append("No results available.")
            continue

        text.append(
            f"Success: {result.get('success')}"
        )
        text.append(
            f"Total Issues: {result.get('total_issues', 0)}"
        )

        issues = result.get("issues") or []

        for issue in issues[:20]:
            if not isinstance(issue, dict):
                continue

            text.append(
                f"- Line {issue.get('line')}: "
                f"{issue.get('message')}"
            )

    if static_results.get("tool") == "Cppcheck":
        text.append("\n=== CPPCHECK ANALYSIS ===")
        text.append(
            f"Total Issues: "
            f"{static_results.get('total_issues', 0)}"
        )

        issues = static_results.get("issues") or []

        for issue in issues[:30]:
            if not isinstance(issue, dict):
                continue

            text.append(
                f"- Line {issue.get('line')}: "
                f"[{issue.get('severity')}] "
                f"{issue.get('message')} "
                f"({issue.get('code')})"
            )

    if static_results.get("tool") == "Checkstyle":
        text.append("\n=== CHECKSTYLE ANALYSIS ===")
        text.append(
            f"Total Issues: "
            f"{static_results.get('total_issues', 0)}"
        )

        issues = static_results.get("issues") or []

        for issue in issues[:30]:
            if not isinstance(issue, dict):
                continue

            text.append(
                f"- Line {issue.get('line')}: "
                f"[{issue.get('severity')}] "
                f"{issue.get('message')}"
            )

    scores = static_results.get("scores") or {}
    text.append("\n=== CODE SCORES ===")

    valid_scores = False

    for metric in [
        "quality",
        "security",
        "complexity",
        "maintainability",
        "overall"
    ]:
        metric_data = scores.get(metric)

        if isinstance(metric_data, dict):
            score = metric_data.get("score")
            valid_scores = True
        elif isinstance(metric_data, (int, float)):
            score = metric_data
            valid_scores = True
        else:
            score = None

        text.append(
            f"{metric.capitalize()}: {score}"
        )

    if not valid_scores:
        text.append("No score results available.")

    issues = static_results.get("issues") or []
    text.append("\n=== CLASSIFIED ISSUES ===")

    if issues:
        for issue in issues[:30]:
            if not isinstance(issue, dict):
                continue

            text.append(
                f"- [{issue.get('severity')}] "
                f"{issue.get('tool')} | "
                f"Line {issue.get('line')} | "
                f"{issue.get('type')} | "
                f"{issue.get('message')}"
            )
    else:
        text.append("No classified issues available.")

    return "\n".join(text)

def process_ai_response(response):
    sections = {
        "bugs": "",
        "quality": "",
        "performance": "",
        "security": "",
        "complexity": "",
        "maintainability": "",
        "suggestions": "",
        "optimized_code": ""
    }

    if not response:
        return sections

    if response.startswith(
        "AI service is currently unavailable"
    ):
        sections["bugs"] = response
        return sections

    if response.startswith(
        "AI analysis timed out"
    ):
        sections["bugs"] = response
        return sections

    if response.startswith(
        "Unable to connect"
    ):
        sections["bugs"] = response
        return sections

    headings = {
        "BUGS:": "bugs",
        "BUGS OR ERRORS:": "bugs",
        "CODE QUALITY:": "quality",
        "PERFORMANCE:": "performance",
        "SECURITY:": "security",
        "COMPLEXITY:": "complexity",
        "MAINTAINABILITY:": "maintainability",
        "SUGGESTIONS:": "suggestions",
        "OPTIMIZED CODE:": "optimized_code"
    }

    current_section = None
    optimized_started = False
    inside_code_block = False

    for raw_line in response.splitlines():
        line = raw_line.strip()

        clean_line = (
            line.replace("#", "")
            .replace("*", "")
            .strip()
            .upper()
        )

        if clean_line in headings:
            current_section = headings[clean_line]

            if current_section == "optimized_code":
                optimized_started = True

            continue

        if not current_section:
            continue

        if current_section == "optimized_code":
            if line.startswith("```"):
                if not inside_code_block:
                    inside_code_block = True
                    continue

                inside_code_block = False
                continue

            if not optimized_started:
                continue

            if inside_code_block:
                sections["optimized_code"] += raw_line + "\n"

            continue

        existing_lines = sections[current_section].splitlines()

        if line and line not in existing_lines:
            sections[current_section] += line + "\n"

    sections["optimized_code"] = sections[
        "optimized_code"
    ].strip()

    return sections